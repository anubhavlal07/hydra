import { cn } from "@/lib/utils";

export function Card({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="card"
      className={cn(
        "flex min-w-0 flex-col rounded-lg border border-line bg-surface p-4 shadow-xs max-wide:p-3.5",
        className,
      )}
      {...props}
    />
  );
}

